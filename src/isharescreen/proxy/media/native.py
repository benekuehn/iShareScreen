"""Native FFmpeg VAAPI contexts; no decoded image buffers cross this ABI.

Keep the existing reference/recovery protocol while replacing its codec
context. A frame owns its Rust handle, which owns an AVFrame reference. EGL
composition independently pins that surface until its GPU fence signals.
"""

from __future__ import annotations

import ctypes as C
import itertools
import functools
import logging
import threading
import os
import sys
import time
from pathlib import Path
from types import SimpleNamespace

_LIB = None
_GENERATIONS = itertools.count(1)
log = logging.getLogger(__name__)
# Synthetic 64x64 black IDR, generated by libx264; SPS/PPS/slice only.
_AVC420_SAMPLE = bytes.fromhex(
    "000000016742c00ada109b011000000300100000030328f1226a0000000168ce0fc8"
    "0000016588843a2628000902c9c9c9d75d75d75d75d75d75e0"
)


def library():
    global _LIB
    if _LIB is not None:
        return _LIB
    default = (
        Path(__file__).resolve().parents[4]
        / "native/target/release/libisharescreen_native.so"
    )
    path = os.environ.get("ISS_NATIVE_LIBRARY", str(default))
    lib = C.CDLL(path)
    signatures = {
        "iss_error": ([], C.c_char_p),
        "iss_decoder_new": (
            [C.c_int, C.c_void_p, C.c_size_t, C.c_char_p, C.c_uint64],
            C.c_void_p,
        ),
        "iss_decoder_send": ([C.c_void_p, C.c_void_p, C.c_size_t, C.c_int64], C.c_int),
        "iss_decoder_receive": ([C.c_void_p], C.c_void_p),
        "iss_decoder_drain": ([C.c_void_p], C.c_int),
        "iss_decoder_flush": ([C.c_void_p], None),
        "iss_decoder_free": ([C.c_void_p], None),
        "iss_frame_free": ([C.c_void_p], None),
        "iss_frame_generation": ([C.c_void_p], C.c_uint64),
        "iss_frame_ready": ([C.c_void_p], C.c_int),
        "iss_frame_wait": ([C.c_void_p], C.c_int),
        "iss_frame_info": ([C.c_void_p, C.POINTER(FrameInfo)], None),
        "iss_renderer_new": ([C.c_int, C.c_int, C.c_uint64], C.c_void_p),
        "iss_renderer_upload": ([C.c_void_p, C.c_void_p, C.c_int, C.c_int], C.c_int),
        "iss_renderer_draw": ([C.c_void_p, C.c_int, C.c_int], C.c_int),
        "iss_renderer_free": ([C.c_void_p], None),
        "iss_udp_new": ([C.c_int, C.c_size_t], C.c_void_p),
        "iss_udp_read": ([C.c_void_p, C.c_void_p, C.c_size_t], C.c_size_t),
        "iss_udp_dropped": ([C.c_void_p], C.c_uint64),
        "iss_udp_free": ([C.c_void_p], None),
        "iss_udp_depth": ([C.c_void_p], C.c_size_t),
    }
    for name, (args, result) in signatures.items():
        fn = getattr(lib, name)
        fn.argtypes, fn.restype = args, result
    _LIB = lib
    return lib


def error(lib):
    return (lib.iss_error() or b"native engine failed").decode(errors="replace")


class FrameInfo(C.Structure):
    _fields_ = [("pts", C.c_int64)] + [
        (name, C.c_int)
        for name in ("width", "height", "error", "full_range", "matrix", "chroma444")
    ]


class NativeUdpReceiver:
    """Bounded encrypted-packet buffer drained by a Rust thread, before auth."""

    def __init__(self, fd, capacity=16384):
        self._lib = library()
        self._handle = self._lib.iss_udp_new(fd, capacity)
        if not self._handle:
            raise RuntimeError("Could not start native UDP receiver")
        self._buffer = C.create_string_buffer(256 * 1024)

    def batch(self):
        size = self._lib.iss_udp_read(self._handle, self._buffer, len(self._buffer))
        data = self._buffer.raw[:size]
        pos = 0
        packets = []
        while pos < size:
            length = int.from_bytes(data[pos : pos + 2], "big")
            pos += 2
            packets.append(data[pos : pos + length])
            pos += length
        return packets

    @property
    def dropped(self):
        return self._lib.iss_udp_dropped(self._handle)

    @property
    def depth(self):
        return self._lib.iss_udp_depth(self._handle)

    def close(self):
        if self._handle:
            self._lib.iss_udp_free(self._handle)
            self._handle = None

    def __del__(self):
        if getattr(self, "_handle", None):
            self.close()


class SurfaceFrame:
    """An opaque GPU surface. Intentionally exposes no y/u/v pixel arrays."""

    def __init__(self, lib, handle):
        self._lib, self.handle = lib, handle
        info = FrameInfo()
        lib.iss_frame_info(handle, C.byref(info))
        self.pts, self.width, self.height = info.pts, info.width, info.height
        self.decode_error_flags, self.flags = info.error, 0
        self.full_range, self.matrix = bool(info.full_range), info.matrix
        self.is_yuv444 = bool(info.chroma444)
        self.generation = lib.iss_frame_generation(handle)
        self.format = SimpleNamespace(name="iss_vaapi")
        self.gpu_surface = True
        self.decoder_output_ns = time.monotonic_ns()
        self.gpu_ready_observed_ns = None

    @property
    def ready(self):
        if self.gpu_ready_observed_ns is not None:
            return True
        status = self._lib.iss_frame_ready(self.handle)
        if status == 1:
            self.gpu_ready_observed_ns = time.monotonic_ns()
        # Unsupported readiness queries use the synchronized upload path;
        # do not label that fallback as a measured GPU completion.
        return status != 0

    def __del__(self):
        handle = getattr(self, "handle", None)
        if handle:
            self._lib.iss_frame_free(handle)
            self.handle = None


class NativeContext:
    is_hwaccel = True
    gpu_surfaces = True

    def __init__(self, codec: str, extradata: bytes):
        self._lib = library()
        self.generation = next(_GENERATIONS)
        self._handle = self._lib.iss_decoder_new(
            0 if codec == "h264" else 1,
            extradata,
            len(extradata),
            os.environ.get("ISS_VAAPI_DEVICE", "/dev/dri/renderD128").encode(),
            self.generation,
        )
        if not self._handle:
            raise RuntimeError(error(self._lib))

    def _receive(self):
        frames = []
        while True:
            handle = self._lib.iss_decoder_receive(self._handle)
            if not handle:
                message = self._lib.iss_error()
                if message:
                    raise RuntimeError(message.decode(errors="replace"))
                return frames
            frame = SurfaceFrame(self._lib, handle)
            if os.environ.get("ISS_NATIVE_SYNC_DECODE", "1") == "1":
                # Wait on the decoder worker, never on GLFW's event thread.
                # Bound in-flight GPU decode instead of replacing unfinished
                # surfaces faster than the GPU can report them complete.
                if self._lib.iss_frame_wait(handle) < 0:
                    raise RuntimeError(error(self._lib))
                frame.gpu_ready_observed_ns = time.monotonic_ns()
            frames.append(frame)

    def decode(self, packet):
        if not self._handle:
            raise RuntimeError("native decoder is closed")
        if packet is None:
            if self._lib.iss_decoder_drain(self._handle) < 0:
                raise RuntimeError(error(self._lib))
            return self._receive()
        data = bytes(packet)
        result = self._lib.iss_decoder_send(
            self._handle, data, len(data), packet.pts or 0
        )
        frames = []
        if result == 1:
            # FFmpeg requires draining output before retrying the SAME packet.
            frames = self._receive()
            result = self._lib.iss_decoder_send(
                self._handle, data, len(data), packet.pts or 0
            )
        if result != 0:
            raise RuntimeError(error(self._lib))
        return frames + self._receive()

    def flush_buffers(self):
        if self._handle:
            self._lib.iss_decoder_flush(self._handle)

    def close(self):
        if self._handle:
            self._lib.iss_decoder_free(self._handle)
            self._handle = None

    def __del__(self):
        if getattr(self, "_handle", None):
            self.close()


@functools.lru_cache(maxsize=2)
def available(codec="hevc"):
    if sys.platform != "linux" or os.environ.get("ISS_NATIVE_GPU") != "1":
        return False
    try:
        context = NativeContext(codec, b"")
        try:
            import av

            if codec == "hevc":
                from .hwcaps import _HEVC444_SAMPLE

                sample = _HEVC444_SAMPLE
            else:
                sample = _AVC420_SAMPLE
            frames = context.decode(av.Packet(sample)) + context.decode(None)
            return bool(frames) and all(
                f.gpu_surface and (codec != "hevc" or f.is_yuv444) for f in frames
            )
        finally:
            context.close()
    except (OSError, RuntimeError) as exc:
        log.debug("native %s probe unavailable: %s", codec, exc)
        return False


def make_decoder(codec, num_tiles, **kwargs):
    from .avc import AvcDecoder
    from .hevc import HevcDecoder

    base = AvcDecoder if codec == "h264" else HevcDecoder

    class NativeDecoder(base):
        def __init__(self, num_tiles, **options):
            from .surface_queue import ReadySurfaces

            self._surface_lock = threading.Lock()
            self._surfaces = [ReadySurfaces() for _ in range(num_tiles)]
            super().__init__(num_tiles, **options)

        def _publish_frame(self, frame):
            frame.decode_submit_ns = int(
                self._pts_submit_t.get(frame.pts, time.monotonic()) * 1e9
            )
            ti = self._pts_to_tile.get(frame.pts)
            if ti is not None:
                with self._surface_lock:
                    self._surfaces[ti].add(frame)
            super()._publish_frame(frame)

        def get_frame(self, tile_idx):
            if codec == "h264":
                return super().get_frame(tile_idx)
            if not self._dpb_has_idr or tile_idx in self._tiles_await_idr:
                return None
            with self._surface_lock:
                frame = self._surfaces[tile_idx].take()
            if frame is not None:
                if frame.decode_error_flags:
                    self._gate.mark_decode_error(tile_idx)
                else:
                    self._gate.mark_clean(tile_idx)
            return frame

        def _teardown(self):
            super()._teardown()
            with self._surface_lock:
                for surface in self._surfaces:
                    surface.frames.clear()

        def presentation_stats(self):
            with self._surface_lock:
                return {
                    key: sum(getattr(queue, key) for queue in self._surfaces)
                    for key in ("published", "taken", "superseded", "not_ready")
                }

        def _try_hwaccel_locked(self, hw_type, extradata):
            return NativeContext(codec, extradata) if hw_type == "vaapi" else None

        def _try_hwaccel(self, hw_type, extradata):
            return NativeContext(codec, extradata) if hw_type == "vaapi" else None

        @staticmethod
        def _make_sw_context(extradata):
            raise RuntimeError(
                "Native GPU decoding failed; reconnect with --frontend desktop for software fallback"
            )

    return NativeDecoder(num_tiles, **kwargs)
